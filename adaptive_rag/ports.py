"""Role contracts. Adapters are injected; importing a role performs no I/O."""

from typing import Any, Protocol, Sequence

from .config import Principal
from .domain import (
    AccessContext, ChildChunk, Coverage, Draft, Evidence, Hit, IngestRequest,
    IngestResult, ParentChunk, Plan, PreparedDocument, QueryRequest,
    Section, Snapshot, SubQuery, Verification,
)
from .trace_history import MAX_CONVERSATION_TURNS


class Parser(Protocol):
    def parse(self, request: IngestRequest) -> tuple[Section, ...]: ...


class Cleaner(Protocol):
    def clean(self, sections: Sequence[Section]) -> tuple[Section, ...]: ...


class Chunker(Protocol):
    def chunk(self, request: IngestRequest, revision_id: str, sections: Sequence[Section]) -> tuple[tuple[ParentChunk, ...], tuple[ChildChunk, ...]]: ...


class ObjectStore(Protocol):
    def put(self, content: bytes) -> str: ...
    def get(self, key: str) -> bytes: ...


class KnowledgeStore(Protocol):
    """Snapshot reads are published-only unless a trusted caller has authorized a candidate preview.

    Preview requires explicit opt-in on manifest and content reads; live access policy still applies.
    """

    def stage(self, document: PreparedDocument, *, principal: Principal | None = None) -> IngestResult: ...
    def check_stage_owner(self, principal: Principal, doc: str) -> None: ...
    def managed_documents(self, principal: Principal, view: str) -> list[dict[str, Any]]: ...
    def managed_document(self, principal: Principal, doc_id: str) -> dict[str, Any]: ...
    def document_source(self, principal: Principal, doc_id: str, revision: str | None = None, *,
                        original: bool = False) -> tuple[str, str, str]: ...
    def trash_document(self, principal: Principal, doc_id: str, expected_generation: str | None) -> dict[str, Any]: ...
    def restore_document(self, principal: Principal, doc_id: str, trash_id: str,
                         expected_generation: str | None) -> dict[str, Any]: ...
    def get_job(self, tenant_id: str, job_id: str) -> dict[str, Any]: ...
    def access_epoch(self, tenant: str) -> int: ...
    def list_documents(self, tenant_id: str) -> list[dict[str, Any]]: ...
    def publish(self, tenant_id: str, job_id: str, expected_generation: str | None, *,
                principal: Principal | None = None) -> Snapshot: ...
    def create_candidate_snapshot(self, tenant_id: str, job_ids: Sequence[str], expected_generation: str | None) -> Snapshot: ...
    def activate_candidate_snapshot(self, tenant_id: str, generation: str, expected_generation: str | None, *,
                                    principal: Principal | None = None) -> Snapshot: ...
    def is_candidate_snapshot(self, tenant_id: str, generation: str) -> bool: ...
    def abandon_candidate_snapshot(self, tenant_id: str, generation: str) -> bool: ...
    def list_prewarm_chunks(self, snapshot: Snapshot, *, allow_candidate: bool = False) -> tuple[ChildChunk, ...]: ...
    def check_prewarm_access(self, tenant_id: str, document_ids: Sequence[str], *, access: AccessContext | None) -> bool: ...
    def open_snapshot(self, tenant_id: str, generation: str | None = None, *, allow_candidate: bool = False) -> Snapshot | None: ...
    def list_chunks(self, snapshot: Snapshot, access: AccessContext, sku: str | None = None, *,
                    allow_candidate: bool = False) -> tuple[ChildChunk, ...]: ...
    def get_parents(self, snapshot: Snapshot, parent_ids: Sequence[str], access: AccessContext, *,
                    allow_candidate: bool = False) -> tuple[ParentChunk, ...]: ...
    def delete_document(self, tenant_id: str, document_id: str, expected_generation: str | None, *,
                        principal: Principal | None = None) -> Snapshot: ...
    def rollback(self, tenant_id: str, generation: str, expected_generation: str | None) -> Snapshot: ...
    def set_access(self, tenant_id: str, document_id: str, allowed_subjects: tuple[str, ...] | None = None,
                   revoked: bool | None = None,
                   data_domains: tuple[str, ...] | None = None, *, principal: Principal | None = None) -> None: ...


class Planner(Protocol):
    async def plan(self, request: QueryRequest) -> Plan: ...


class QueryTransform(Protocol):
    async def transform(self, queries: Sequence[SubQuery], request: QueryRequest) -> tuple[SubQuery, ...]: ...


class Retriever(Protocol):
    async def search(self, query: SubQuery, chunks: Sequence[ChildChunk], limit: int) -> tuple[Hit, ...]: ...


class Fusion(Protocol):
    def fuse(self, query: SubQuery, lanes: Sequence[Sequence[Hit]], limit: int) -> tuple[Hit, ...]: ...


class Reranker(Protocol):
    async def rank(self, query: SubQuery, hits: Sequence[Hit], limit: int) -> tuple[Hit, ...]: ...


class EvidenceJudge(Protocol):
    async def assess(self, queries: Sequence[SubQuery], evidence: Sequence[Evidence]) -> Coverage: ...


class Generator(Protocol):
    async def generate(self, plan: Plan, evidence: Sequence[Evidence]) -> Draft: ...


class Verifier(Protocol):
    async def verify(self, draft: Draft, evidence: Sequence[Evidence]) -> Verification: ...


class AnswerVerifier(Verifier, Protocol):
    """Optional semantic review; original questions are required to check omissions."""
    async def evaluate(self, plan: Plan, draft: Draft, evidence: Sequence[Evidence]) -> Verification: ...


class Embedder(Protocol):
    """Future cloud adapter. Document/query encoders must share model revision."""
    async def embed(self, texts: Sequence[str]) -> tuple[tuple[float, ...], ...]: ...


class DecisionPolicy(Protocol):
    """Request-local rule or intent policy; output never grants access or raises budgets."""
    async def decide(self, state: dict[str, Any]) -> dict[str, Any]: ...


class TraceSink(Protocol):
    def save(self, trace: dict[str, Any], *, conversation_id: str | None = None) -> None: ...
    def get(self, tenant_id: str, trace_id: str) -> dict[str, Any]: ...
    def list_conversations(self, tenant_id: str, subject_id: str, limit: int, offset: int) -> list[dict[str, Any]]:
        """Newest first: conversation_id, first surviving trace_id, latest UTC started_at as updated_at."""
        ...
    def conversation_turns(self, tenant_id: str, subject_id: str, conversation_id: str, *,
                           limit: int = MAX_CONVERSATION_TURNS + 1) -> list[str]:
        """At most limit surviving IDs, ordered by start time then trace ID; one extra ID detects overflow."""
        ...
